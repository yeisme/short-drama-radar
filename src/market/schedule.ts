// Which readiness states may be collected by a scheduled observation pass.
// planned/identity_verified have no verified sample; blocked is explicitly
// out. Nothing here bypasses a qualification decision.
const OBSERVABLE_READINESS: readonly SourceReadiness[] = ["sample_verified", "qualified"];

export interface MarketSourceRunState {
  source_ref: string;
  readiness: SourceReadiness;
  /** Last attempt time of any outcome, used only for ordering/reporting. */
  last_attempt_at?: string | null;
  /** Risk-control cooldown (login failure / captcha); observation is skipped until it passes. */
  cooldown_until?: string | null;
}

export interface MarketObservationPlan {
  spec: "radar.market_observation_plan.v1";
  policy: typeof MARKET_OBSERVE_POLICY;
  waves: string[][];
  skipped: Array<{ source_ref: string; reason: "qualification_pending" | "blocked" | "risk_control_cooldown" }>;
  attempts_per_source: number;
  retry_backoff_ms: number[];
}

// Pure run plan: eligible sources in deterministic order, executed in
// concurrency-bounded waves. Replay after a suspend/resume produces the same
// plan for the still-eligible sources — batch digests keep re-runs from
// duplicating observations (see repository.saveObservationBatch).
export function planMarketObservationRun(states: MarketSourceRunState[], now = new Date()): MarketObservationPlan {
  if (!Number.isFinite(now.getTime())) throw new Error("planMarketObservationRun requires a valid clock.");
  const skipped: MarketObservationPlan["skipped"] = [];
  const eligible: MarketSourceRunState[] = [];
  for (const state of states) {
    if (state.cooldown_until && Date.parse(state.cooldown_until) > now.getTime()) {
      skipped.push({ source_ref: state.source_ref, reason: "risk_control_cooldown" });
    } else if (state.readiness === "blocked") {
      skipped.push({ source_ref: state.source_ref, reason: "blocked" });
    } else if (!OBSERVABLE_READINESS.includes(state.readiness)) {
      skipped.push({ source_ref: state.source_ref, reason: "qualification_pending" });
    } else {
      eligible.push(state);
    }
  }
  eligible.sort((a, b) =>
    a.last_attempt_at === b.last_attempt_at
      ? a.source_ref.localeCompare(b.source_ref)
      : (a.last_attempt_at ? Date.parse(a.last_attempt_at) : 0) - (b.last_attempt_at ? Date.parse(b.last_attempt_at) : 0));
  const waves: string[][] = [];
  for (let i = 0; i < eligible.length; i += MARKET_OBSERVE_POLICY.global_concurrency) {
    waves.push(eligible.slice(i, i + MARKET_OBSERVE_POLICY.global_concurrency).map(s => s.source_ref));
  }
  return {
    spec: "radar.market_observation_plan.v1",
    policy: MARKET_OBSERVE_POLICY,
    waves,
    skipped,
    attempts_per_source: 1 + MARKET_OBSERVE_POLICY.max_read_retries,
    retry_backoff_ms: [...MARKET_OBSERVE_POLICY.retry_backoff_ms],
  };
}

export type MarketSourceRunErrorCode =
  | "source_unavailable"
  | "source_auth_required"
  | "source_risk_control"
  | "source_timeout";

export interface MarketSourceRunResult {
  source_ref: string;
  outcome: "observed" | "failed" | "incomplete";
  error_code?: MarketSourceRunErrorCode;
  completed_at?: string;
}

export interface MarketRunFreezeDecision {
  spec: "radar.market_run_freeze.v1";
  freeze: true;
  brief_status: "ready" | "degraded" | "empty";
  incomplete_sources: string[];
  failed_sources: string[];
  reasons: string[];
}

// Cutoff decision: a source task that has not finished by the cutoff never
// blocks the edition — the brief freezes partial with named gaps. Bounded
// failure is the honest state; "waiting a bit longer" is not available.
export function resolveMarketRunFreeze(results: MarketSourceRunResult[], opts: { cutoff: string }): MarketRunFreezeDecision {
  const cutoffMs = Date.parse(opts.cutoff);
  if (!Number.isFinite(cutoffMs)) throw new Error("resolveMarketRunFreeze requires a valid cutoff.");
  const incomplete = results.filter(r => r.outcome === "incomplete" ||
    (r.completed_at !== undefined && Date.parse(r.completed_at) > cutoffMs));
  const failed = results.filter(r => r.outcome === "failed");
  const reasons: string[] = [];
  if (incomplete.length) reasons.push("Source tasks did not finish before the cutoff; the edition froze without them.");
  if (failed.length) reasons.push("Failed sources are reported per source; other sources still contributed.");
  const contributing = results.filter(r => r.outcome === "observed");
  return {
    spec: "radar.market_run_freeze.v1",
    freeze: true,
    brief_status: contributing.length ? (incomplete.length || failed.length ? "degraded" : "ready") : "empty",
    incomplete_sources: incomplete.map(r => r.source_ref),
    failed_sources: failed.map(r => r.source_ref),
    reasons,
  };
}

export type RetryDecision = { retry: true; delay_ms: number } | { retry: false; cooldown_hours?: number; reason: string };

// Read-only transport failures retry with the bounded backoff; login and
// risk-control failures never retry automatically and enter the 24h cooldown.
export function marketRetryDecision(errorCode: MarketSourceRunErrorCode, attempt: number): RetryDecision {
  if (errorCode === "source_auth_required" || errorCode === "source_risk_control") {
    return { retry: false, cooldown_hours: MARKET_OBSERVE_POLICY.risk_control_cooldown_hours,
      reason: "Login or risk-control failures never auto-retry; owner review is required." };
  }
  if (attempt >= 1 + MARKET_OBSERVE_POLICY.max_read_retries) {
    return { retry: false, reason: "Read-only retry budget exhausted for this source." };
  }
  return { retry: true, delay_ms: MARKET_OBSERVE_POLICY.retry_backoff_ms[attempt - 1] ?? MARKET_OBSERVE_POLICY.retry_backoff_ms.at(-1)! };
}
