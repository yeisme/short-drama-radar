import type { SourceReadiness } from "./domain.ts";

// Owner schedule description for the market pipeline. Unit generation is
// pure; installing/enabling timers is an explicit owner action and nothing
// here starts, enables or claims an already-running scheduler.
//
// Design §5: the market pipeline gets schedule units separate from the
// legacy collect/score/card timers, ordinary reads never trigger collection,
// failures are bounded, and a source task that misses its cutoff freezes a
// partial brief instead of blocking the edition.

export const MARKET_OBSERVE_POLICY = {
  // Two observation slots per day, 12h apart (local time).
  slots_per_day: 2,
  slot_spacing_hours: 12,
  // Bounded read-only collection per source.
  source_timeout_ms: 60_000,
  max_read_retries: 2,
  retry_backoff_ms: [2_000, 8_000],
  global_concurrency: 2,
  // Login failures / captcha never auto-retry; risk control cools down 24h.
  risk_control_cooldown_hours: 24,
} as const;

// Local times stay clear of the legacy collect/score/card morning block so
// the two schedules never fight over the shared SQLite lock.
export const MARKET_SCHEDULE_TIMES = { analyze: "08:50", brief: "09:00" } as const;

export interface MarketScheduleUnits {
  [unitName: string]: string;
}

function onCalendar(time: string): string {
  const m = time.match(/^(\d{1,2}):(\d{2})$/);
  if (!m) return `*-*-* ${time}`;
  return `*-*-* ${String(m[1]).padStart(2, "0")}:${m[2]}:00`;
}

// Units for the locally runnable market pass: analyze the previous complete
// local day, then freeze the brief. `observe` stays a planned stage until a
// source passes qualification and the owner CLI exposes it; generating an
// observe timer before that would schedule a command that must refuse to run.
export function buildMarketScheduleUnits(execStart: string): MarketScheduleUnits {
  const env = [
    `Environment=RADAR_HOME=%h/.short-drama-radar`,
    `Environment="PATH=${(process.env.PATH ?? "/usr/local/bin:/usr/bin:/bin").replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("%", "%%")}"`,
  ].join("\n");
  // Same flock discipline as the legacy units: market services share the
  // radar SQLite file and serialize on the existing lock instead of fighting.
  const service = (name: string, description: string, command: string, after: string[] = []) => `# Generated by radar market schedule install — do not edit by hand.
[Unit]
Description=${description}${after.length > 0 ? `\n${after.map((u) => `After=${u}\nWants=${u}`).join("\n")}` : ""}

[Service]
Type=oneshot
ExecStart=/usr/bin/flock -w 600 %h/.short-drama-radar/radar.lock ${execStart} ${command} --json
${env}
# Output goes to the journal; the envelope carries no secrets.
NoNewPrivileges=yes
PrivateTmp=yes
`;
  const timer = (description: string, time: string, serviceName: string) => `# Generated by radar market schedule install — do not edit by hand.
[Unit]
Description=${description}

[Timer]
OnCalendar=${onCalendar(time)}
Persistent=true
Unit=${serviceName}

[Install]
WantedBy=timers.target
`;
  return {
    "short-drama-radar-market-analyze.service":
      service("market-analyze", "short-drama-radar market: analyze the previous complete local day", "market analyze"),
    "short-drama-radar-market-analyze.timer":
      timer("short-drama-radar market: analyze before the daily brief", MARKET_SCHEDULE_TIMES.analyze, "short-drama-radar-market-analyze.service"),
    "short-drama-radar-market-brief.service":
      service("market-brief", "short-drama-radar market: freeze the daily market brief", "market brief build", ["short-drama-radar-market-analyze.service"]),
    "short-drama-radar-market-brief.timer":
      timer("short-drama-radar market: brief freeze at the configured local time", MARKET_SCHEDULE_TIMES.brief, "short-drama-radar-market-brief.service"),
  };
}

